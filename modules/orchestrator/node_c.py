def _remediation_for(fingerprint: str) -> str:
    """Assemble targeted fix instructions for every gate named in the fingerprint."""
    remedies = [advice for key, advice in _FINGERPRINT_REMEDIES if key in fingerprint]
    if not remedies:
        return "- Re-read the module contract and regenerate the full file from scratch.\n"
    return "".join(f"- {advice}\n" for advice in remedies)


def _build_prompt(
    execution_plan: str,
    failure_count: int,
    fingerprint: str,
    references: list[tuple[str, str]],
    architecture_mode: str,
    paper_text: str = "",
) -> str:
    retry_section = ""
    if failure_count > 0 and fingerprint:
        retry_section = (
            "RETRY CONTEXT (SELF-HEALING, attempt "
            f"{failure_count + 1}):\n"
            f"- error_fingerprint: {fingerprint}\n"
            "- TARGETED FIXES REQUIRED:\n"
            f"{_remediation_for(fingerprint)}"
            "- Regenerate the ENTIRE file with these fixes applied; do not repeat the failing pattern.\n\n"
        )

    if references:
        formatted_refs = []
        for name, src in references:
            snippet = src[:1200]
            formatted_refs.append(f"REFERENCE: {name}\n```python\n{snippet}\n```")
        refs_section = "\n\n".join(formatted_refs)
    else:
        refs_section = "(no AST references available)"

    system_prompt = PINN_SYSTEM_PROMPT if architecture_mode == "continuous_pinn" else CNN_SYSTEM_PROMPT

    framework_section = ""
    if architecture_mode == "continuous_pinn":
        framework_template = _load_framework_template()
        if framework_template:
            framework_section = (
                "FRAMEWORK REFERENCE (PyTorch Best Practices):\n"
                f"{framework_template}\n\n"
            )

    if paper_text:
        paper_section = f"PROVIDED PAPER TEXT (cite sections/pages from THIS text only):\n{paper_text}\n\n"
    else:
        paper_section = (
            "PROVIDED PAPER TEXT: none available -- mark all traceability sections as UNAVAILABLE.\n\n"
        )

    return (
        f"{system_prompt}"
        f"{framework_section}"
        f"{paper_section}"
        f"EXECUTION PLAN:\n{execution_plan}\n\n"
        f"{retry_section}"
        f"GOLDEN REFERENCE SNIPPETS (AST-indexed, structurally validated):\n{refs_section}\n"
    )


def _try_generate_with_gemini(prompt: str, model_names: tuple[str, ...] | None = None) -> str | None:
    """Attempt live Gemini generation; return None on any non-fatal failure."""
    global _SKIP_LLM_FOR_SESSION

    _load_env_file_if_present()

    if _SKIP_LLM_FOR_SESSION:
        LOGGER.warning(
            "Node C: skipping live Gemini calls for this process after repeated model availability failures"
        )
        return None

    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        LOGGER.warning("Node C: GEMINI_API_KEY not found; using deterministic fallback template")
        return None
    if genai is None:
        LOGGER.warning("Node C: google-genai is unavailable; using deterministic fallback template")
        return None

    try:
        client = genai.Client(api_key=api_key)
    except Exception as exc:
        LOGGER.warning("Node C: failed to initialize Gemini client (%s); using fallback", exc)
        return None

    selected_models = model_names or _resolve_model_names()
    if not selected_models:
        selected_models = DEFAULT_GEMINI_MODELS

    all_failures_not_found_or_deprecated = True

    for model_name in selected_models:
        try:
            response = client.models.generate_content(model=model_name, contents=prompt)
            text = getattr(response, "text", None) or ""
            code = extract_python_code(text)
            if code:
                return code
            LOGGER.warning("Node C: empty generation from model '%s'; trying fallback model", model_name)
            all_failures_not_found_or_deprecated = False
        except Exception as exc:
            LOGGER.warning("Node C: generation failed for model '%s' (%s)", model_name, exc)
            all_failures_not_found_or_deprecated = (
                all_failures_not_found_or_deprecated and _is_not_found_or_deprecated(exc)
            )

    if all_failures_not_found_or_deprecated:
        _SKIP_LLM_FOR_SESSION = True
        LOGGER.warning(
            "Node C: all configured Gemini models appear unavailable/deprecated. "
            "Using deterministic fallback for the rest of this process. "
            "Set GEMINI_MODELS to current IDs (e.g. gemini-2.5-pro,gemini-2.5-flash)."
        )
    return None


def node_c_framework_supervisor(state: AgentState) -> dict:
    """Generate (or regenerate, on retry) the monolith from the execution plan."""
    execution_plan = state.get("execution_plan", "")
    architecture_mode = state.get("architecture_mode", "cnn_field")
    failure_count = state.get("failure_count", 0)
    fingerprint = state.get("error_fingerprint", "")

    references = _fetch_golden_references(limit=4, execution_plan=execution_plan)
    reference_names = ", ".join(name for name, _ in references) or "(AST index unavailable)"

    paper_text = _load_paper_text(str(state.get("paper_id", "")))
    if paper_text:
        LOGGER.info("Node C: grounding prompt with extracted paper text (%s chars)", len(paper_text))
    else:
        LOGGER.warning(
            "Node C: no extracted paper text found for paper_id=%s; traceability sections will be UNAVAILABLE",
            state.get("paper_id", ""),
        )

    if failure_count > 0 and fingerprint:
        retry_note = (
            f"RETRY CONTEXT: previous attempt failed with fingerprint '{fingerprint}'. "
            "The code below has been regenerated to address it."
        )
    else:
        retry_note = "First-pass generation from the execution plan."

    prompt = _build_prompt(
        execution_plan=execution_plan,
        failure_count=failure_count,
        fingerprint=fingerprint,
        references=references,
        architecture_mode=architecture_mode,
        paper_text=paper_text,
    )

    code = _try_generate_with_gemini(prompt)
    if code:
        LOGGER.info(
            "Node C: live LLM generation succeeded (attempt %s, %s chars, %s refs)",
            failure_count + 1, len(code), len(references),
        )
    else:
        LOGGER.warning(
            "Node C: using deterministic fallback template (attempt %s, fingerprint=%s)",
            failure_count + 1, fingerprint or "None",
        )
        if architecture_mode == "continuous_pinn":
            code = _fallback_pinn_monolith(
                failure_count=failure_count,
                retry_note=retry_note,
                reference_names=reference_names,
            )
        else:
            code = _fallback_monolith(
                failure_count=failure_count,
                retry_note=retry_note,
                reference_names=reference_names,
            )
    return {"generated_code": code}
