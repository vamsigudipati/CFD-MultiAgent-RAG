def _resolve_model_names() -> tuple[str, ...]:
    """Resolve model names from env override or use safe defaults.

    `GEMINI_MODELS` supports a comma-separated list, e.g.:
    GEMINI_MODELS="gemini-2.5-pro,gemini-2.5-flash"
    """
    override = os.environ.get("GEMINI_MODELS", "").strip()
    if not override:
        return DEFAULT_GEMINI_MODELS
    models = tuple(m.strip() for m in override.split(",") if m.strip())
    return models or DEFAULT_GEMINI_MODELS


def _load_env_file_if_present() -> None:
    """Load simple KEY=VALUE pairs from repo-local .env into process env.

    Existing environment variables are not overwritten.
    """
    if not ENV_FILE_PATH.is_file():
        return

    try:
        for raw in ENV_FILE_PATH.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            key = key.strip()
            value = value.strip().strip('"').strip("'")
            if key and key not in os.environ:
                os.environ[key] = value
    except Exception as exc:
        LOGGER.warning("Node C: failed to read .env file at %s (%s)", ENV_FILE_PATH, exc)


def _is_not_found_or_deprecated(exc: Exception) -> bool:
    msg = str(exc).lower()
    return (
        "404" in msg
        or "not_found" in msg
        or "is not found" in msg
        or "no longeravailable" in msg
        or "no longer available" in msg
        or "deprecated" in msg
    )


def extract_python_code(raw_text: str) -> str:
    """Extract Python code from fenced blocks; fall back to raw output if absent."""
    if not raw_text:
        return ""

    matches = re.findall(r"```(?:python|py)?\s*(.*?)```", raw_text, flags=re.IGNORECASE | re.DOTALL)
    if not matches:
        LOGGER.warning("Node C LLM output had no fenced code block; using raw text fallback")
        return raw_text.strip()

    # Prefer the longest code block in case the model emits multiple snippets.
    return max(matches, key=len).strip()


